package messaging

import "testing"

func TestWeChatEmphasis(t *testing.T) {
	for _, tt := range []struct{ in, want string }{
		{"**粗体中有 *斜体 Italic***", "**粗体中有** ***斜体 Italic***"},
		{"**检查 _外观_ 和包装**", "**检查** ***外观*** **和包装**"},
		{"**检查 *外观***，**记录 _批次_**。", "**检查** ***外观***，**记录** ***批次***。"},
		{"*斜体* ／ **粗体** ／ ***粗斜体***", "*斜体* ／ **粗体** ／ ***粗斜体***"},
		{"**保留 SKU_AB_12**", "**保留 SKU_AB_12**"},
		{"**包装 `*原文*`**", "**包装 `*原文*`**"},
		{"[示例](url/**段 _原文_**)", "[示例](url/**段 _原文_**)"},
		{"**粗体中有 *斜体 Italic***，见[说明](https://example.com)", "**粗体中有** ***斜体 Italic***，见[说明](https://example.com)"},
		{"\\*原样\\*，**检查 _数量_**", "\\*原样\\*，**检查** ***数量***"},
		{"\\**保留 *原文***，**检查 *数量***", "\\**保留 *原文***，**检查** ***数量***"},
		{"**保留 \\# *原文***，**检查 *数量***", "**保留 \\# *原文***，**检查** ***数量***"},
		{"| **检查 *数量*** | [说明](url(a)/x \"括号 ) **字 _原文_**\") | **复查 _外观_** |", "| **检查** ***数量*** | [说明](url(a)/x \"括号 ) **字 _原文_**\") | **复查** ***外观*** |"},
		{"\\*\\*原文 *星号***", "\\*\\*原文 *星号***"},
		{"**数量 2 * 3 * 4**", "**数量 2 * 3 * 4**"},
		{"***数量 *不配对***", "***数量 *不配对***"},
		{"**检查 *数量_**", "**检查 *数量_**"},
	} {
		if got := weChatEmphasis(tt.in); got != tt.want {
			t.Errorf("weChatEmphasis(%q) = %q, want %q", tt.in, got, tt.want)
		} else if next := weChatEmphasis(got); next != got {
			t.Errorf("second pass changed %q to %q", got, next)
		}
	}
}
